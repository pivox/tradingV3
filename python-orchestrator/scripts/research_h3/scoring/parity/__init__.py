"""Golden vectors v1 of the H3 scoring engine, for a future PHP port (byte-identical outputs required).

``golden_v1.json`` (generated by ``build_golden``, checked by ``verify_golden`` in the tests) holds, in the
contracts' wire form:
- ``arithmetic``: the arithmetic rules of ``scoring.arith`` the port must follow (scale 18, truncation toward zero,
  integer square root, operation order as written in the engine and feature formulas);
- ``feature_spec``: the catalogue id, version and fingerprint the vectors were made with;
- ``cost_model``: the CostModel every score case uses;
- ``feature_cases``: raw inputs (bars, including a forming bar and a bar received after the decision, quotes,
  funding) -> expected FeatureSnapshot wire;
- ``manifests`` / ``snapshots``: shared inputs, referenced by key;
- ``score_cases``: (manifest key or null, snapshot key, candidate wire) -> expected OpportunityScore wire, its
  fingerprint and the estimation trace (every intermediate number, to locate a divergence);
- ``rank_cases``: scores in a given input order -> expected ranked output (candidate id, rank and the fingerprint
  of each output score).

A port is conformant when, for every case, the canonical JSON of its output equals the expected one byte for byte.
Every input here is synthetic (``scoring.fixtures``); the "calibrated" manifests are labelled SYNTHETIC TEST
FIXTURES. Regenerate only together with a catalogue or engine version change:
``python -m scripts.research_h3.scoring.parity --write``; ``--check`` verifies the committed file.
"""
